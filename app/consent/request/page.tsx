
import { getTranslations } from "@/lib/i18n/server";
export async function generateMetadata() {
  const { t } = await getTranslations();
  return {
  title: t("Согласие на обработку данных — Mercy"),
  robots: {
    index: false,
    follow: false,
  },
};
}

export default async function RequestConsentPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | undefined>>;
}) {
  const { t } = await getTranslations();

  const params = await searchParams;
  const isGeorgia = params.country === "ge";

  return (
    <main className="page-shell section legal-page">
      <h1>{t("Согласие на обработку данных обращения")}</h1>

      {isGeorgia ? <GeorgiaConsent /> : <RussiaConsent />}
    </main>
  );
}

